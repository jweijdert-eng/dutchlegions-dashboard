import { chromium } from 'playwright-core'
const APP=`http://localhost:${process.env.PORT??8081}`
const b=await chromium.launch({channel:'msedge',headless:true})
const J=(o)=>({status:200,headers:{'access-control-allow-origin':'*','content-type':'application/json'},body:JSON.stringify(o)})
const ctx=await b.newContext({viewport:{width:1300,height:900},deviceScaleFactor:2})
await ctx.addInitScript(()=>localStorage.setItem('eve_tokens',JSON.stringify([{accessToken:'f',refreshToken:'f',expiresAt:Date.now()+7200000,characterId:1831618559,characterName:'Desk Tester'}])))
await ctx.route('**/characters/1831618559/',r=>r.fulfill(J({name:'Desk Tester',corporation_id:98652891,alliance_id:99013537,birthday:'2012-05-10T00:00:00Z',security_status:3.4})))
await ctx.route('**/characters/1831618559/wallet/**',r=>r.fulfill(J(12480000000)))
await ctx.route('**/characters/1831618559/wallet/journal/**',r=>r.fulfill(J([{id:1,date:new Date().toISOString(),ref_type:'bounty_prizes',amount:45000000},{id:2,date:new Date().toISOString(),ref_type:'market_transaction',amount:12000000}])))
await ctx.route('**/characters/1831618559/skillqueue/**',r=>r.fulfill(J([{skill_id:3327,finished_level:5,start_date:new Date(Date.now()-3600000).toISOString(),finish_date:new Date(Date.now()+7200000).toISOString()}])))
await ctx.route('**/characters/1831618559/industry/jobs/**',r=>r.fulfill(J([])))
await ctx.route('**/characters/1831618559/orders/**',r=>r.fulfill(J([])))
await ctx.route('**/characters/1831618559/calendar/**',r=>r.fulfill(J([])))
await ctx.route('**/corporations/98652891/',r=>r.fulfill(J({name:'Dutch Legions',ticker:'DLEG',member_count:80})))
await ctx.route('**/alliances/99013537/',r=>r.fulfill(J({name:'Test Alliance',ticker:'TEST'})))
await ctx.route('**/universe/names/**',r=>{const ids=JSON.parse(r.request().postData()||'[]');return r.fulfill(J(ids.map(id=>({id,name:'Spaceship Command',category:'x'}))))})
await ctx.route('**zkillboard.com/**',r=>r.fulfill(J([])))
await ctx.route('**/status/**',r=>r.fulfill(J({players:28412,server_version:'x',vip:false})))
await ctx.route('**images.evetech.net/**',r=>r.fulfill({status:200,headers:{'access-control-allow-origin':'*'},body:''}))
const page=await ctx.newPage()
await page.goto(`${APP}/`,{waitUntil:'networkidle'}).catch(()=>{})
await page.waitForTimeout(1800)
const t=await page.locator('body').innerText()
console.log('HERO: naam zichtbaar?', t.includes('Desk Tester'))
console.log('HERO: wallet ~12.48B?', /12\.48B/.test(t))
console.log('HERO: canvas (sterrenveld) aanwezig?', await page.locator('canvas').count()>0)
await page.screenshot({path:'.verify-shots/dashboard-hero.png'})
await b.close()
